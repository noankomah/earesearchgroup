import json
from pathlib import Path
from collections import defaultdict
from django.core.exceptions import ValidationError
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from django.db.models import BooleanField
from django.utils import timezone
from django.utils.dateparse import parse_datetime
from website import models
from website.content import rich_text

def decoded(value, default):
    if not isinstance(value, str):
        return value if value is not None else default
    try:
        return json.loads(value)
    except (TypeError, ValueError):
        return default

def timestamp(value):
    if not value:
        return None
    result = parse_datetime(value)
    return timezone.make_aware(result) if result and timezone.is_naive(result) else result

class Command(BaseCommand):
    help = "Import a private JSON export from the PHP site. Re-running updates records by legacy ID."
    def add_arguments(self, parser):
        parser.add_argument("export_file", type=Path)
        parser.add_argument("--dry-run", action="store_true")

    @transaction.atomic
    def handle(self, *args, **options):
        try:
            data = json.loads(options["export_file"].read_text())
        except (OSError, ValueError) as error:
            raise CommandError("Cannot read the JSON export.") from error
        if data.get("format") != "earg-legacy-v1" or not isinstance(data.get("tables"), dict):
            raise CommandError("Expected an earg-legacy-v1 export generated by tools/export_legacy.php.")
        tables = data["tables"]
        counts = {}
        try:
            for table, model in [("publications", models.Publication), ("opportunities", models.Opportunity), ("contact_messages", models.ContactMessage)]:
                fields = {f.name: f for f in model._meta.fields}
                count = 0
                for row in tables.get(table, []):
                    obj, _ = model.objects.get_or_create(legacy_id=int(row["id"]), defaults=self.defaults(model, row))
                    for key, field in fields.items():
                        if key in {"id", "legacy_id", "owner", "editor_group", "created_at", "updated_at"} or key not in row:
                            continue
                        value = row[key]
                        if isinstance(field, BooleanField):
                            value = str(value).lower() in {"true", "1"}
                        elif value is None:
                            value = None if field.null else ""
                        if key in {"full_content", "full_description"}:
                            value = str(rich_text(value))
                        setattr(obj, key, value)
                    if model is models.ContactMessage:
                        obj.is_read = row.get("status") in {"Read", "Archived"}
                        obj.is_archived = row.get("status") == "Archived"
                    obj.full_clean()
                    obj.save()
                    dates = {field: timestamp(row.get(field)) for field in ["created_at", "updated_at"] if field in fields and row.get(field)}
                    if dates:
                        model.objects.filter(pk=obj.pk).update(**dates)
                    if model is models.Publication:
                        gallery = decoded(row.get("gallery_images"), [])
                        if not isinstance(gallery, list):
                            raise ValueError("Publication gallery must be a list")
                        obj.images.all().delete()
                        for order, path in enumerate(gallery):
                            image = models.PublicationImage(publication=obj, image_path=path, order=order)
                            image.full_clean()
                            image.save()
                    count += 1
                counts[table] = count
            for row in tables.get("newsletter_subscribers", []):
                email = row["email"].strip().lower()
                obj, _ = models.NewsletterSubscriber.objects.get_or_create(email=email)
                obj.full_clean()
                date = timestamp(row.get("created_at"))
                if date:
                    models.NewsletterSubscriber.objects.filter(pk=obj.pk).update(subscribed_at=date)
            counts["newsletter_subscribers"] = len(tables.get("newsletter_subscribers", []))
            for row in tables.get("founder_story", []):
                story, _ = models.FounderStory.objects.update_or_create(pk=1, defaults={
                    "founder_name": row.get("founder_name") or "Founder", "role_title": row.get("role_title") or "",
                    "photo_url": row.get("photo_url") or "", "is_published": str(row.get("is_published", "0")) == "1"})
                story.full_clean()
                story.sections.all().delete()
                sections = decoded(row.get("sections"), [{"heading": "", "body": row.get("sections") or ""}])
                if not isinstance(sections, list):
                    raise ValueError("Founder sections must be a list")
                for order, section in enumerate(sections):
                    models.StorySection.objects.create(story=story, heading=section.get("heading", ""), body=str(rich_text(section.get("body", ""))), order=order)
            counts["founder_story"] = len(tables.get("founder_story", []))
            answers = defaultdict(lambda: defaultdict(list))
            for row in tables.get("survey_answers", []):
                answers[int(row["response_id"])][row["question_key"]].append(row["value"])
            survey = models.Survey.objects.filter(slug="mentorship").first()
            if tables.get("survey_responses") and not survey:
                raise CommandError("Run seed_site before importing survey responses.")
            snapshot = list(survey.questions.values("key", "title", "type", "options")) if survey else []
            checkbox_keys = {q["key"] for q in snapshot if q["type"] == "checkbox"}
            for row in tables.get("survey_responses", []):
                values = {key: value if key in checkbox_keys else value[0] for key, value in answers[int(row["id"])].items()}
                obj, _ = models.SurveyResponse.objects.update_or_create(legacy_id=int(row["id"]), defaults={"survey": survey, "answers": values, "question_snapshot": snapshot})
                date = timestamp(row.get("submitted_at"))
                if date:
                    models.SurveyResponse.objects.filter(pk=obj.pk).update(submitted_at=date)
            counts["survey_responses"] = len(tables.get("survey_responses", []))
        except (ValidationError, ValueError, KeyError, TypeError) as error:
            raise CommandError(f"Import rolled back: {error}") from error
        if options["dry_run"]:
            transaction.set_rollback(True)
        for table, count in counts.items():
            self.stdout.write(f"{table}: {count}")
        if data.get("missing_tables"):
            self.stdout.write(self.style.WARNING("Tables absent from source: " + ", ".join(data["missing_tables"])))
        self.stdout.write(self.style.SUCCESS("Dry run passed; no changes saved." if options["dry_run"] else "Import complete. Uploaded files must be copied separately."))

    def defaults(self, model, row):
        # Minimal defaults needed for first creation, followed by complete validation above.
        if model is models.ContactMessage:
            return {"full_name": row.get("full_name") or "", "email": row.get("email") or "", "message": row.get("message") or ""}
        return {"title": row["title"], "slug": row["slug"]}
